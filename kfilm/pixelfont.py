W, H = 5, 7


def width(text: str, scale: int = 1, spacing: int = 1) -> int:
    return max(0, len(text) * (W + spacing) - spacing) * scale


def draw(img: Image.Image, xy, text: str, scale: int = 2, fill=(255, 255, 255),
         spacing: int = 1, shadow=None) -> int:
    """Draw `text` at xy; returns the x after it. `shadow`: a colour drawn
    one pixel-cell down and right first, for that chunky screen look."""
    d = ImageDraw.Draw(img)
    x0, y0 = xy
    if shadow is not None:
        draw(img, (x0 + scale, y0 + scale), text, scale, shadow, spacing)
    x = x0
    for ch in text.upper():
        g = _G.get(ch, _G["?"])
        if len(g) < W * H:
            g = g.ljust(W * H, ".")
        for i, c in enumerate(g[: W * H]):
            if c == "#":
                px, py = x + (i % W) * scale, y0 + (i // W) * scale
                d.rectangle([px, py, px + scale - 1, py + scale - 1], fill=fill)
        x += (W + spacing) * scale
    return x
